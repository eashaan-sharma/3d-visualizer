# Builds dist/3d-visualizer-offline.html: the whole app in ONE file that works by
# double-clicking (file://), with no server and no internet.
#
# Why this works without a bundler: browsers refuse to load module FILES from file:// pages,
# but they happily run modules given as data: URLs. So every module is base64-encoded into a
# data: URL, and the page's import map points each import name at its data: URL. Relative
# imports ('./arcball.js') are first rewritten to unique names ('@/js/arcball.js') so they can
# be listed in the import map. CSS and the sample .obj models are inlined too.
#
# Run from the project folder:  powershell -ExecutionPolicy Bypass -File tools\build-offline.ps1
$ErrorActionPreference = 'Stop'
$root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$utf8 = New-Object System.Text.UTF8Encoding $false
function Read-Text($rel) { [IO.File]::ReadAllText((Join-Path $root $rel), $utf8) }

# Import name -> source file (paths relative to the project folder).
$modules = [ordered]@{
  'three'                               = 'lib/three/three.module.js'
  '@/lib/three/three.core.js'           = 'lib/three/three.core.js'
  'three/addons/RoomEnvironment.js'     = 'lib/three/addons/RoomEnvironment.js'
  'three/addons/VertexNormalsHelper.js' = 'lib/three/addons/VertexNormalsHelper.js'
  'lil-gui'                             = 'lib/lil-gui/lil-gui.esm.js'
}
Get-ChildItem (Join-Path $root 'js') -Recurse -Filter *.js | ForEach-Object {
  $rel = $_.FullName.Substring($root.Length + 1).Replace('\', '/')
  $modules["@/$rel"] = $rel
}

# Rewrite  from './x.js'  /  from '../x.js'  to  from '@/<path from project root>'.
$relativeImport = [regex]"(\bfrom\s*)(['""])(\.{1,2}/[^'""]+)\2"
$imports = [ordered]@{}
foreach ($name in $modules.Keys) {
  $rel = $modules[$name]
  $dir = [IO.Path]::GetDirectoryName($rel).Replace('\', '/')
  $code = $relativeImport.Replace((Read-Text $rel), {
    param($m)
    $full = [IO.Path]::GetFullPath((Join-Path (Join-Path $root $dir) $m.Groups[3].Value))
    $target = '@/' + $full.Substring($root.Length + 1).Replace('\', '/')
    if (-not $modules.Contains($target)) { throw "Unresolved import $($m.Groups[3].Value) in $rel" }
    $m.Groups[1].Value + $m.Groups[2].Value + $target + $m.Groups[2].Value
  })
  $imports[$name] = 'data:text/javascript;base64,' + [Convert]::ToBase64String($utf8.GetBytes($code))
}

$importMap = @{ imports = $imports } | ConvertTo-Json -Compress
$models = [ordered]@{}
Get-ChildItem (Join-Path $root 'models') -Filter *.obj | ForEach-Object { $models["models/$($_.Name)"] = Read-Text "models/$($_.Name)" }
$modelsJson = $models | ConvertTo-Json -Compress

$html = Read-Text 'index.html'
$html = $html.Replace('<link rel="stylesheet" href="css/style.css">', "<style>`n$(Read-Text 'css/style.css')</style>")
$html = [regex]::Replace($html, '<script type="importmap">[\s\S]*?</script>', { "<script type=""importmap"">$importMap</script>" })
$html = $html.Replace('<script type="module" src="js/main.js"></script>',
  "<script>window.EMBEDDED_MODELS = $modelsJson;</script>`n  <script type=""module"">import '@/js/main.js';</script>")
$html = $html.Replace('<meta charset="utf-8">', "<meta charset=""utf-8"">`n  <!-- Single-file offline build, generated by tools/build-offline.ps1. Edit the source files instead. -->")

$out = Join-Path $root 'dist/3d-visualizer-offline.html'
New-Item -ItemType Directory -Force (Split-Path $out) | Out-Null
[IO.File]::WriteAllText($out, $html, $utf8)
Write-Host ("Wrote {0} ({1:N1} MB, {2} modules)" -f $out, ((Get-Item $out).Length / 1MB), $modules.Count)
